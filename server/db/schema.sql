CREATE SCHEMA IF NOT EXISTS probashi_shield;
REVOKE ALL ON SCHEMA probashi_shield FROM PUBLIC;

CREATE TABLE IF NOT EXISTS probashi_shield.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role TEXT NOT NULL DEFAULT 'worker' CHECK (role IN ('worker', 'nominee', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email ON probashi_shield.users (LOWER(email));

CREATE TABLE IF NOT EXISTS probashi_shield.agencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_no VARCHAR(50) NOT NULL,
    name VARCHAR(200) NOT NULL,
    status TEXT NOT NULL DEFAULT 'flagged' CHECK (status IN ('verified', 'flagged', 'revoked')),
    risk_score SMALLINT CHECK (risk_score BETWEEN 0 AND 255),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_agencies_license_no
    ON probashi_shield.agencies (LOWER(license_no));

CREATE TABLE IF NOT EXISTS probashi_shield.corridors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(100) NOT NULL,
    country_code CHAR(2) UNIQUE,
    job_category VARCHAR(100),
    max_legal_fee_bdt NUMERIC(12, 2) CHECK (max_legal_fee_bdt >= 0),
    min_expected_salary_bdt NUMERIC(12, 2),
    max_expected_salary_bdt NUMERIC(12, 2),
    corridor_risk_level TEXT CHECK (corridor_risk_level IN ('low', 'medium', 'high')),
    rule_source VARCHAR(500),
    effective_date DATE
);

CREATE INDEX IF NOT EXISTS ix_corridors_country_category
    ON probashi_shield.corridors (LOWER(country), job_category);

CREATE TABLE IF NOT EXISTS probashi_shield.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES probashi_shield.users (id),
    agency_id BIGINT REFERENCES probashi_shield.agencies (id),
    corridor_id BIGINT REFERENCES probashi_shield.corridors (id),
    document_type TEXT NOT NULL,
    file_path VARCHAR(1024),
    sha256 CHAR(64),
    extracted_data JSONB,
    extraction_status TEXT NOT NULL DEFAULT 'pending' CHECK (
        extraction_status IN ('pending', 'needs_confirmation', 'confirmed', 'failed')
    ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (worker_id, sha256)
);

ALTER TABLE probashi_shield.documents
    ADD COLUMN IF NOT EXISTS extraction_method TEXT CHECK (extraction_method IN ('manual_fallback', 'gemini'));

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'probashi_shield.documents'::regclass AND conname = 'ck_documents_type'
    ) THEN
        ALTER TABLE probashi_shield.documents
            DROP CONSTRAINT IF EXISTS documents_document_type_check,
            ADD CONSTRAINT ck_documents_type CHECK (
                document_type IN ('job_offer', 'offer_letter', 'receipt', 'demand_letter', 'contract', 'visa', 'other')
            );
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS ix_documents_agency ON probashi_shield.documents (agency_id);
CREATE INDEX IF NOT EXISTS ix_documents_corridor ON probashi_shield.documents (corridor_id);

CREATE TABLE IF NOT EXISTS probashi_shield.audit_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES probashi_shield.documents (id) ON DELETE CASCADE,
    related_document_id BIGINT REFERENCES probashi_shield.documents (id) ON DELETE SET NULL,
    check_type VARCHAR(80) NOT NULL,
    rule_version VARCHAR(40) NOT NULL,
    result TEXT NOT NULL CHECK (result IN ('passed', 'warning', 'failed', 'needs_review')),
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_audit_checks_document
    ON probashi_shield.audit_checks (document_id);
CREATE INDEX IF NOT EXISTS ix_audit_checks_related_document
    ON probashi_shield.audit_checks (related_document_id);

CREATE TABLE IF NOT EXISTS probashi_shield.journeys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES probashi_shield.users (id),
    corridor_id BIGINT NOT NULL REFERENCES probashi_shield.corridors (id),
    nominee_id BIGINT REFERENCES probashi_shield.users (id) ON DELETE SET NULL,
    nominee_consent_token_hash CHAR(64) UNIQUE,
    nominee_consent_expires_at TIMESTAMP,
    overall_status TEXT NOT NULL DEFAULT 'in_progress',
    payment_frozen BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_journeys_worker ON probashi_shield.journeys (worker_id);
CREATE INDEX IF NOT EXISTS ix_journeys_corridor ON probashi_shield.journeys (corridor_id);
CREATE INDEX IF NOT EXISTS ix_journeys_nominee ON probashi_shield.journeys (nominee_id);

CREATE TABLE IF NOT EXISTS probashi_shield.journey_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_id BIGINT NOT NULL REFERENCES probashi_shield.journeys (id) ON DELETE CASCADE,
    step_name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    completed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (journey_id, step_name)
);

DO $$
BEGIN
    IF EXISTS (SELECT FROM information_schema.columns WHERE table_schema = 'probashi_shield'
               AND table_name = 'journeys' AND column_name = 'payments_frozen') THEN
        ALTER TABLE probashi_shield.journeys DROP CONSTRAINT journeys_status_check;
        ALTER TABLE probashi_shield.journeys RENAME COLUMN status TO overall_status;
        ALTER TABLE probashi_shield.journeys RENAME COLUMN payments_frozen TO payment_frozen;
        UPDATE probashi_shield.journeys SET overall_status = 'blocked_recovery' WHERE overall_status = 'blocked';
    END IF;
    IF EXISTS (SELECT FROM information_schema.columns WHERE table_schema = 'probashi_shield'
               AND table_name = 'journey_steps' AND column_name = 'stage') THEN
        ALTER TABLE probashi_shield.journey_steps DROP CONSTRAINT journey_steps_stage_check,
            DROP CONSTRAINT journey_steps_status_check;
        ALTER TABLE probashi_shield.journey_steps RENAME COLUMN stage TO step_name;
        ALTER TABLE probashi_shield.journey_steps
            ALTER COLUMN completed_at TYPE TIMESTAMPTZ USING completed_at AT TIME ZONE 'UTC',
            ALTER COLUMN expires_at TYPE TIMESTAMPTZ USING expires_at AT TIME ZONE 'UTC';
        UPDATE probashi_shield.journey_steps SET step_name = 'immigration_clearance' WHERE step_name = 'immigration';
        UPDATE probashi_shield.journey_steps SET step_name = 'flight' WHERE step_name = 'flight_readiness';
        UPDATE probashi_shield.journey_steps SET status = 'passed' WHERE status = 'completed';
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid = 'probashi_shield.journeys'::regclass
                   AND conname = 'ck_journey_overall_status') THEN
        ALTER TABLE probashi_shield.journeys ADD CONSTRAINT ck_journey_overall_status
            CHECK (overall_status IN ('in_progress', 'blocked_recovery', 'ready_for_flight', 'completed'));
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid = 'probashi_shield.journey_steps'::regclass
                   AND conname = 'ck_journey_step_status') THEN
        ALTER TABLE probashi_shield.journey_steps ADD CONSTRAINT ck_journey_step_status
            CHECK (status IN ('pending', 'in_progress', 'passed', 'failed', 'expired', 'reopened'));
    END IF;
END;
$$;

ALTER TABLE probashi_shield.journeys
    ADD COLUMN IF NOT EXISTS agency_id BIGINT REFERENCES probashi_shield.agencies (id),
    ADD COLUMN IF NOT EXISTS flight_ready BOOLEAN NOT NULL DEFAULT FALSE;

-- Derive order from the name so a stage cannot be stored with conflicting prerequisites.
ALTER TABLE probashi_shield.journey_steps
    ADD COLUMN IF NOT EXISTS step_order INTEGER GENERATED ALWAYS AS (
        array_position(ARRAY['agency_verification', 'medical', 'police_clearance', 'training',
                             'immigration_clearance', 'visa', 'flight'], step_name)
    ) STORED NOT NULL,
    ADD COLUMN IF NOT EXISTS retry_count INTEGER NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    ADD COLUMN IF NOT EXISTS notes TEXT;

CREATE INDEX IF NOT EXISTS ix_journey_steps_status_expiry
    ON probashi_shield.journey_steps (status, expires_at);

CREATE OR REPLACE FUNCTION probashi_shield.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER set_updated_at
    BEFORE UPDATE ON probashi_shield.journeys
    FOR EACH ROW EXECUTE FUNCTION probashi_shield.set_updated_at();

CREATE OR REPLACE TRIGGER set_updated_at
    BEFORE UPDATE ON probashi_shield.journey_steps
    FOR EACH ROW EXECUTE FUNCTION probashi_shield.set_updated_at();

CREATE TABLE IF NOT EXISTS probashi_shield.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES probashi_shield.users (id) ON DELETE SET NULL,
    target_user_id BIGINT REFERENCES probashi_shield.users (id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(60) NOT NULL,
    entity_id BIGINT NOT NULL,
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_audit_logs_entity
    ON probashi_shield.audit_logs (entity_type, entity_id, created_at);
CREATE INDEX IF NOT EXISTS ix_audit_logs_actor ON probashi_shield.audit_logs (actor_id);
CREATE INDEX IF NOT EXISTS ix_audit_logs_target_user ON probashi_shield.audit_logs (target_user_id);
